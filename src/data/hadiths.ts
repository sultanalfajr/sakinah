/** حديث الليلة — ثابت طوال اليوم، يتبدل كل يوم */
export function hadithOfTheNight(): Hadith {
  const now = new Date();
  const dayIndex = Math.floor(
    now.getTime() / (1000 * 60 * 60 * 24)
  );
  return HADITHS[dayIndex % HADITHS.length];
}
